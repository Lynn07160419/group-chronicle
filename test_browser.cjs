const {chromium}=require('/Users/lynn/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8766');
  await page.waitForFunction(()=>document.querySelector('#recordCount').textContent==='273');
  await page.locator('#search').fill('彩虹团');
  assert.equal(await page.locator('#results tr').count(),3);
  await page.locator('#semesterFilter').selectOption('08-09上学期');
  await page.locator('#dayFilter').selectOption('周五');
  assert.equal(await page.locator('#results tr').count(),1);
  await page.locator('#reset').click();
  await page.locator('#newName').fill('小ＦＵＮ团');
  assert.equal(await page.locator('#save').isDisabled(),true);
  assert.match(await page.locator('#nameStatus').innerText(),/小饭团/);
  await page.locator('#newName').fill('浏览器验收专用团');
  await page.locator('#newDay').selectOption('周四');
  await page.locator('#save').click();
  await page.waitForFunction(()=>document.querySelector('#saveStatus').textContent.includes('已保存'));
  assert.equal(await page.locator('#results tr').count(),1);
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('#recordCount').textContent==='274');
  await page.locator('#search').fill('浏览器验收专用团');
  assert.equal(await page.locator('#results tr').count(),1);
  await page.locator('#newName').fill('浏览器验收专用团');
  assert.equal(await page.locator('#save').isDisabled(),true);
  await page.locator('#reset').click();await page.locator('#newName').fill('');
  await page.screenshot({path:'/tmp/group-archive-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.screenshot({path:'/tmp/group-archive-mobile.png',fullPage:true});
  // Exercise optional WebMCP registration through a compatible test shim.
  await page.addInitScript(()=>{window.archiveTools={};Object.defineProperty(document,'modelContext',{value:{registerTool(t){window.archiveTools[t.name]=t;}}});});
  await page.reload();await page.waitForFunction(()=>window.archiveTools.search_group_archive);
  assert.equal(await page.evaluate(async()=> (await window.archiveTools.search_group_archive.execute({name:'彩虹团',weekday:'周五'})).length),2);
  assert.equal(await page.evaluate(async()=>{try{await window.archiveTools.search_group_archive.execute({weekday:'周八'});return false}catch{return true}}),true);
  assert.deepEqual(errors,[]);
  await browser.close();console.log('Browser checks passed: search, combined filters, aliases, create, reload, duplicates, mobile width, optional tool contract.');
})().catch(e=>{console.error(e);process.exit(1)});
